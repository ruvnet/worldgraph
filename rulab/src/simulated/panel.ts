import { createElement, ChevronRight, Download, Upload, X } from 'lucide';
import { loadRolloutIndex, openBundledRollout } from './bundled';
import { RolloutGraph } from './graph';
import { loadRolloutFiles, verifyRollout } from './manifest';
import type { RolloutBundle, RolloutPhase, RolloutPlaybackState, VerifiedRollout } from './types';

/** The permanent label of every simulated rollout. Tests assert this exact text. */
export const ROLLOUT_BANNER = 'SIMULATED · MODEL PREDICTION · NOT A CAPTURE';

export interface RolloutPanelOptions {
  /** The `.workspace` element; the dialog and overlay are appended to it. */
  readonly workspace: HTMLElement;
  /** The rail button that opens the picker. */
  readonly trigger: HTMLElement;
  /** Vite base URL, ending in a slash. */
  readonly base: string;
  readonly notify: (message: string) => void;
  readonly download: (name: string, data: string) => void;
}
export interface RolloutPanel {
  openPicker(): void;
  close(): void;
  dispose(): void;
}

